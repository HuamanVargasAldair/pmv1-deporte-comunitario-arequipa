class PostgresActividadRepository:
    def __init__(self):
        self.database_url = os.environ.get('DATABASE_URL')
        if not self.database_url:
            raise RuntimeError('Falta configurar la variable DATABASE_URL.')

        self._init_db()

    @contextmanager
    def _connect(self):
        with psycopg.connect(
            self.database_url,
            row_factory=dict_row,
            connect_timeout=10,
        ) as con:
            yield con

    def _init_db(self):
        with self._connect() as con:
            con.execute("""
                CREATE TABLE IF NOT EXISTS actividades (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    deporte TEXT NOT NULL,
                    nombre TEXT NOT NULL,
                    distrito TEXT NOT NULL,
                    dia TEXT NOT NULL,
                    hora TEXT NOT NULL,
                    cupos_totales INTEGER NOT NULL CHECK (cupos_totales > 0),
                    inscritos INTEGER NOT NULL DEFAULT 0
                        CHECK (inscritos >= 0 AND inscritos <= cupos_totales),
                    gratuita BOOLEAN NOT NULL DEFAULT FALSE
                )
            """)
            con.execute("""
                CREATE TABLE IF NOT EXISTS inscripciones (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    actividad_id BIGINT NOT NULL REFERENCES actividades(id),
                    nombre TEXT NOT NULL,
                    correo TEXT NOT NULL,
                    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    UNIQUE (actividad_id, correo)
                )
            """)
            count = con.execute(
                'SELECT COUNT(*) AS total FROM actividades'
            ).fetchone()['total']

            if count == 0:
                con.executemany("""
                    INSERT INTO actividades
                    (deporte, nombre, distrito, dia, hora,
                     cupos_totales, inscritos, gratuita)
                    VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                """, [
                    (*row[:7], bool(row[7]))
                    for row in SEED
                ])

    @staticmethod
    def _obj(row):
        if row is None:
            return None
        return Actividad(
            id=row['id'],
            deporte=row['deporte'],
            nombre=row['nombre'],
            distrito=row['distrito'],
            dia=row['dia'],
            hora=row['hora'],
            cupos_totales=row['cupos_totales'],
            inscritos=row['inscritos'],
            gratuita=row['gratuita'],
        )

    def listar(self, distrito=None, deporte=None):
        sql = 'SELECT * FROM actividades WHERE TRUE'
        params = []

        if distrito and distrito != 'Todos':
            sql += ' AND distrito = %s'
            params.append(distrito)

        if deporte and deporte != 'Todos':
            sql += ' AND deporte = %s'
            params.append(deporte)

        sql += ' ORDER BY id'

        with self._connect() as con:
            rows = con.execute(sql, params).fetchall()
            return [self._obj(row) for row in rows]

    def obtener(self, actividad_id):
        with self._connect() as con:
            row = con.execute(
                'SELECT * FROM actividades WHERE id = %s',
                (actividad_id,),
            ).fetchone()
            return self._obj(row)

    def inscribir(self, actividad_id, nombre, correo):
        with self._connect() as con:
            with con.transaction():
                row = con.execute(
                    'SELECT * FROM actividades WHERE id = %s FOR UPDATE',
                    (actividad_id,),
                ).fetchone()

                if row is None:
                    raise LookupError('No se encontró la actividad solicitada.')

                actividad = self._obj(row)
                actividad.validar_inscripcion()

                try:
                    con.execute("""
                        INSERT INTO inscripciones
                        (actividad_id, nombre, correo)
                        VALUES (%s, %s, %s)
                    """, (actividad_id, nombre, correo))
                except psycopg.errors.UniqueViolation:
                    raise ValueError(
                        'Este correo ya está inscrito en esta actividad.'
                    ) from None

                con.execute("""
                    UPDATE actividades
                    SET inscritos = inscritos + 1
                    WHERE id = %s
                """, (actividad_id,))

                updated = con.execute(
                    'SELECT * FROM actividades WHERE id = %s',
                    (actividad_id,),
                ).fetchone()

                return self._obj(updated)
